# -*- coding: utf-8 -*-
"""生成自包含 HTML 测试报告（内联 SVG 环形图 / 分套件条形 / 用例明细表）。"""
import os
import html


def _donut(passed, failed, total):
    if total == 0:
        return ""
    r = 54
    circ = 2 * 3.14159265 * r
    plen = (passed / total) * circ
    rate = passed / total * 100
    return (f'<svg width="160" height="160" viewBox="0 0 160 160">'
            f'<circle cx="80" cy="80" r="{r}" fill="none" stroke="#e74c3c" stroke-width="22"/>'
            f'<circle cx="80" cy="80" r="{r}" fill="none" stroke="#27ae60" stroke-width="22" '
            f'stroke-dasharray="{plen:.1f} {circ:.1f}" transform="rotate(-90 80 80)"/>'
            f'<text x="80" y="76" text-anchor="middle" font-size="22" fill="#222">{rate:.0f}%</text>'
            f'<text x="80" y="98" text-anchor="middle" font-size="12" fill="#666">通过率</text>'
            f'</svg>')


def _bars(suites):
    rows = ""
    for name, s in suites.items():
        total = s["total"] or 1
        pw = s["passed"] / total * 100
        fw = s["failed"] / total * 100
        rows += (f'<div class="bar-row"><span class="bar-name">{html.escape(name)}</span>'
                 f'<div class="bar"><div class="bar-pass" style="width:{pw:.0f}%"></div>'
                 f'<div class="bar-fail" style="width:{fw:.0f}%"></div></div>'
                 f'<span class="bar-leg">{s["passed"]}通过 / {s["failed"]}失败</span></div>')
    return rows


def _table(results):
    rows = ""
    for r in results:
        cls = "ok" if r["outcome"] == "passed" else "bad"
        err = html.escape(r["error"])[:400].replace("\n", "<br/>") if r["error"] else ""
        rows += (f'<tr class="{cls}"><td>{html.escape(r["name"])}</td>'
                 f'<td>{r["outcome"]}</td><td>{r["duration"] * 1000:.0f} ms</td>'
                 f'<td class="err">{err}</td></tr>')
    return rows


def generate_report(total, passed, failed, suites, results, path):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    rate = (passed / total * 100) if total else 0
    css = """
    *{box-sizing:border-box} body{font-family:-apple-system,'Segoe UI',Roboto,'Microsoft YaHei',sans-serif;
      background:#f5f6f8;color:#222;margin:0} .wrap{max-width:960px;margin:24px auto;padding:0 16px}
    h1{font-size:22px;margin:0 0 16px} .kpi{display:flex;gap:12px;flex-wrap:wrap;margin-bottom:18px}
    .card{flex:1;min-width:120px;background:#fff;border-radius:10px;padding:14px 16px;text-align:center;
      box-shadow:0 1px 3px rgba(0,0,0,.08)} .card .num{font-size:26px;font-weight:700}
    .card.green .num{color:#27ae60} .card.red .num{color:#e74c3c}
    .charts{display:flex;gap:18px;flex-wrap:wrap;background:#fff;border-radius:10px;padding:18px;
      box-shadow:0 1px 3px rgba(0,0,0,.08);margin-bottom:18px}
    .chart-box{flex:1;min-width:280px} .chart-box h3{font-size:15px;margin:0 0 10px}
    .bar-row{display:flex;align-items:center;gap:10px;margin:8px 0}
    .bar-name{width:150px;font-size:13px;color:#444;white-space:nowrap;overflow:hidden;text-overflow:ellipsis}
    .bar{flex:1;height:16px;background:#eee;border-radius:8px;overflow:hidden;display:flex}
    .bar-pass{background:#27ae60} .bar-fail{background:#e74c3c}
    .bar-leg{width:96px;font-size:12px;color:#666;text-align:right}
    table{width:100%;border-collapse:collapse;background:#fff;border-radius:10px;overflow:hidden;
      box-shadow:0 1px 3px rgba(0,0,0,.08)} th,td{padding:9px 12px;text-align:left;font-size:13px;
      border-bottom:1px solid #eee} th{background:#2c3e50;color:#fff} tr.ok td:first-child{border-left:3px solid #27ae60}
    tr.bad td:first-child{border-left:3px solid #e74c3c} .err{color:#b03a2e;font-family:monospace;font-size:12px}
    footer{color:#999;font-size:12px;margin:16px 0;text-align:center}
    """
    doc = f"""<!DOCTYPE html><html lang="zh"><head><meta charset="utf-8">
<title>自动化测试报告</title><style>{css}</style></head><body><div class="wrap">
<h1>自动化测试报告</h1>
<div class="kpi">
  <div class="card"><div class="num">{total}</div><div>用例总数</div></div>
  <div class="card green"><div class="num">{passed}</div><div>通过</div></div>
  <div class="card red"><div class="num">{failed}</div><div>失败</div></div>
  <div class="card"><div class="num">{rate:.1f}%</div><div>通过率</div></div>
</div>
<div class="charts">
  <div class="chart-box" style="text-align:center">{_donut(passed, failed, total)}</div>
  <div class="chart-box"><h3>分套件结果</h3>{_bars(suites)}</div>
</div>
<h2>用例明细</h2>
<table><thead><tr><th>用例</th><th>结果</th><th>耗时</th><th>错误信息</th></tr></thead>
<tbody>{_table(results)}</tbody></table>
<footer>Generated by test-automation-framework · pytest + 自研可视化报告</footer>
</div></body></html>"""
    with open(path, "w", encoding="utf-8") as f:
        f.write(doc)
